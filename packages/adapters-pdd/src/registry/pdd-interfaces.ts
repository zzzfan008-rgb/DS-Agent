const UNSPECIFIED = '待填（docs/01 原表该格未细化，需按附录 A3 逐接口核验）';

function todo(detail: string): string {
  return `待填：${detail}`;
}

interface EntryInput {
  key: string;
  section: PddInterfaceSection;
  row: number;
  title: string;
  purpose: string;
  write: boolean;
  operationLevel: PddWriteLevel;
  actionCode: string | null;
  fallback: PddFallbackChannel;
  conclusion: PddInterfaceConclusion;
  conclusionRaw: string;
  todos: PddInterfaceTodos;
  notes?: string;
}

function entry(input: EntryInput): PddInterfaceSpec {
  return {
    key: input.key,
    section: input.section,
    row: input.row,
    title: input.title,
    purpose: input.purpose,
    doc_ref: `docs/01 §${input.section} 第${input.row}行`,
    write: input.write,
    operation_level: input.operationLevel,
    action_code: input.actionCode,
    fallback: input.fallback,
    conclusion: input.conclusion,
    conclusion_raw: input.conclusionRaw,
    verification: 'unverified',
    platform_method: null,
    platform_version: null,
    path_template: null,
    todos: input.todos,
    last_verified_at: null,
    verified_by: null,
    ...(input.notes ? { notes: input.notes } : {}),
  };
}

